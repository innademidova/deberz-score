const cap = (s) => s[0].toUpperCase() + s.slice(1);

let ALL = null;
export function teamNames() {
  if (ALL) return ALL;
  const out = new Set(FIXED);
  for (const a of ADJ) for (const n of PL) out.add(`${a} ${n}`);
  for (const n of PL) for (const g of GEN) { out.add(`${cap(n)} ${g}`); out.add(`${cap(n)} с ${g}`); }
  for (const n of SG) for (const g of GEN) out.add(`${n} с ${g}`);
  ALL = [...out].filter((s) => s.length <= 24); // поле названия — до 24 символов
  return ALL;
}

// Случайное название, не совпадающее с уже занятыми (без учёта регистра).
export function randomTeamName(taken = [], rnd = Math.random) {
  const list = teamNames();
  const busy = new Set(taken.map((t) => String(t).trim().toLowerCase()));
  for (let k = 0; k < 50; k++) { const n = list[Math.floor(rnd() * list.length)]; if (!busy.has(n.toLowerCase())) return n; }
  return list[Math.floor(rnd() * list.length)];
}
